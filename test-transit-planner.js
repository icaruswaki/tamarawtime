'use strict';
const assert=require('node:assert/strict');
const graph=require('./assets/transit/local_transit_graph.json');
const fares=require('./assets/transit/rail_fares_reviewed.json');
const originalFetch=global.fetch;
global.window=global;
let footCalls=0;
global.fetch=async url=>{
 const value=String(url);
 if(value.endsWith('local_transit_graph.json'))return {ok:true,json:async()=>graph};
 if(value.endsWith('rail_fares_reviewed.json'))return {ok:true,json:async()=>fares};
 assert(value.includes('routed-foot'),'Only the pedestrian router is used for station access');
 footCalls++;
 const pair=new URL(value).pathname.split('/driving/')[1].split('?')[0].split(';').map(point=>point.split(',').map(Number));
 return {ok:true,json:async()=>({code:'Ok',routes:[{distance:500,duration:300,geometry:{coordinates:pair}}]})};
};
require('./transit-planner.js');
(async()=>{
 assert.equal(graph.status,'reviewed_network_model');
 assert.equal(graph.stops.length,51);
 assert(graph.edges.length>=95);
 assert(graph.transfers.length>=6);
 const from=graph.stops.find(s=>s.id==='LRT-1:Fernando Poe Jr.').access_coordinates;
 const to=graph.stops.find(s=>s.id==='LRT-1:Monumento').access_coordinates;
 const result=await TamarawTransit.estimate({lat:from[1],lng:from[0]},{lat:to[1],lng:to[0]},'Train');
 assert(result.options.length>0,'A connected reviewed rail route should be found');
 assert.deepEqual(result.options[0].lines,['LRT-1']);
 assert.equal(result.options[0].totalSeconds,null,'No train timetable means no total ETA');
 assert.equal(result.options[0].fare,null,'No reviewed LRT-1 fare means no fare quote');
 assert(footCalls>=2,'Station access and exit require pedestrian routes');
 const katipunan=graph.stops.find(s=>s.id==='LRT-2:Katipunan').access_coordinates;
 const santolan=graph.stops.find(s=>s.id==='LRT-2:Santolan').access_coordinates;
 const lrt2=await TamarawTransit.estimate({lat:katipunan[1],lng:katipunan[0]},{lat:santolan[1],lng:santolan[0]},'Train');
 assert.equal(lrt2.options[0].fare?.amount,8,'Use the reviewed LRT-2 stored-value matrix when the station pair is covered');
 const fpj=graph.stops.find(s=>s.id==='LRT-1:Fernando Poe Jr.').access_coordinates;
 const cubao=graph.stops.find(s=>s.id==='LRT-2:Araneta Center-Cubao').access_coordinates;
 const transfer=await TamarawTransit.estimate({lat:fpj[1],lng:fpj[0]},{lat:cubao[1],lng:cubao[0]},'Train');
 assert(transfer.options.some(o=>o.edges.some(e=>e.vehicle==='WALK')&&o.lines.length>1),'Use reviewed station transfers only when a pedestrian connector is returned');
 console.log('PASS: reviewed graph, station access, reviewed transfer connector, LRT-2 fare matrix, no invented LRT-1 ETA or fare');
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(()=>{global.fetch=originalFetch;});
