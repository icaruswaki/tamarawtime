-- Tamaraw Time pilot: run ONCE in Supabase > SQL Editor.
-- Every student signs in with Supabase Auth. No service-role key in the site.

create table if not exists public.app_states (
  user_id uuid primary key references auth.users(id) on delete cascade,
  payload jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.activity_events (
  id bigint generated always as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  event_type text not null check (event_type in (
    'task_added','task_completed','task_reopened','task_deleted',
    'class_added','class_deleted','commute_saved','settings_saved',
    'maps_opened','gps_checked'
  )),
  occurred_at timestamptz not null default now()
);
create index if not exists activity_events_user_date
  on public.activity_events(user_id, occurred_at desc);

create table if not exists public.feedback (
  user_id uuid primary key references auth.users(id) on delete cascade,
  respondent_code text not null default '' check (char_length(respondent_code) <= 30),
  overall smallint not null check (overall between 1 and 5),
  ease smallint not null check (ease between 1 and 5),
  feature text not null check (char_length(feature) between 1 and 100),
  comments text not null check (char_length(btrim(comments)) between 1 and 1000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.set_tamaraw_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  return new;
end;
$$;
drop trigger if exists app_states_updated_at on public.app_states;
create trigger app_states_updated_at before update on public.app_states
for each row execute function public.set_tamaraw_updated_at();
drop trigger if exists feedback_updated_at on public.feedback;
create trigger feedback_updated_at before update on public.feedback
for each row execute function public.set_tamaraw_updated_at();

-- This function can read activity records to enforce the three-day requirement,
-- but lives in a NON-EXPOSED schema and only checks the authenticated user.
create schema if not exists private;
create or replace function private.tamaraw_eligible_for_feedback()
returns boolean language sql stable security definer set search_path = '' as $$
  select count(distinct (occurred_at at time zone 'Asia/Manila')::date) >= 3
  from public.activity_events
  where user_id = (select auth.uid());
$$;
revoke all on function private.tamaraw_eligible_for_feedback() from public;
grant usage on schema private to authenticated;
grant execute on function private.tamaraw_eligible_for_feedback() to authenticated;

alter table public.app_states enable row level security;
alter table public.activity_events enable row level security;
alter table public.feedback enable row level security;

revoke all on public.app_states from public, anon, authenticated;
revoke all on public.activity_events from public, anon, authenticated;
revoke all on public.feedback from public, anon, authenticated;
grant select, insert, update on public.app_states to authenticated;
grant select, insert (user_id,event_type) on public.activity_events to authenticated;
grant select, insert (user_id,respondent_code,overall,ease,feature,comments),
      update (user_id,respondent_code,overall,ease,feature,comments) on public.feedback to authenticated;

create policy "Read own planner" on public.app_states for select to authenticated
  using ((select auth.uid()) = user_id);
create policy "Create own planner" on public.app_states for insert to authenticated
  with check ((select auth.uid()) = user_id);
create policy "Update own planner" on public.app_states for update to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

create policy "Read own activity" on public.activity_events for select to authenticated
  using ((select auth.uid()) = user_id);
create policy "Log own activity" on public.activity_events for insert to authenticated
  with check ((select auth.uid()) = user_id);
-- No update or delete permissions for student activity logs. Event dates are
-- generated by Postgres on the server, not supplied by the browser.

create policy "Read own feedback" on public.feedback for select to authenticated
  using ((select auth.uid()) = user_id);
create policy "Submit feedback after 3 active days" on public.feedback for insert to authenticated
  with check ((select auth.uid()) = user_id
      and (select private.tamaraw_eligible_for_feedback()));
create policy "Edit own feedback" on public.feedback for update to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id
      and (select private.tamaraw_eligible_for_feedback()));

